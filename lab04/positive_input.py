print("Повторный ввод")
x = int(input("Введите целое число: "))
fail = 0

if x > 0:
    print("-----------")
    print(f"Квадрат числа: {x**2}")
    print(f"Количество ошибок: {fail}")
    print("-----------")
else:
    while x <= 0:
        fail += 1
        print("Попробуй ещё раз")
        x = int(input("Введите целое число: "))
    print("----------")
    print(f"Квадрат числа: {x ** 2}")
    print(f"Количество ошибок: {fail}")
    print("-----------")
